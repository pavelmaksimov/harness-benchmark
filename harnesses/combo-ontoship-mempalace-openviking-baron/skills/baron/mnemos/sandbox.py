#: Доза контрольной руки. Отдельным именем, потому что по ней отличается не
#: только сэмплинг, но и сам факт трипа: у контроля тега `state:trip` нет.
DOSE_NONE = "none"

#: Штатный порог Г1 «факт допустим» (mnemos.gates.CONF_PASS). Дублируется
#: константой, а не импортом, чтобы модуль конфигурации не тянул за собой
#: движок гейтов: здесь нужна только точка отсчёта «доза не отличается».
