# --------------------------------------------------------------------------- #
# Карантин: кто из узлов принадлежит песочнице (TS.1)
# --------------------------------------------------------------------------- #
def _tags_of(node: Any) -> List[str]:
    """Теги узла. Принимаем снимок-словарь, объект с `.get`, объект с `.tags`.

    Чекпойнт и выгрузка отдают узлы словарями, стор — объектами; предикат
    карантина обязан работать в обоих местах, иначе он защитит только одно.
    """
    if node is None:
        return []
    getter = getattr(node, "get", None)
    if callable(getter):
        raw = getter("tags")
    else:
        raw = getattr(node, "tags", None)
    if raw is None:
        return []
    if isinstance(raw, str):
        # Битый снимок, где теги пришли одной строкой. Считаем её одним тегом:
        # посимвольный разбор строки "state:trip" дал бы узлу пустой набор
        # тегов, и узел трипа уехал бы наружу как обычный.
        raw = [raw]
    out: List[str] = []
    for tag in raw:
        text = str(tag)
        # Клиент иногда кладёт ВЕСЬ список тегов одним элементом-JSON: тот же
        # случай, что чинит norm_tags в tools/obsidian/export.py. Выгрузка его
        # разворачивает, и если карантин этого не сделает, узел трипа уедет в
        # vault пользователя с тегами #thread/sandbox и #state/trip — то есть
        # именно там, где его быть не должно.
        if text.startswith("[") and text.endswith("]"):
            try:
                inner = json.loads(text)
            except (ValueError, TypeError):
                inner = None
            if isinstance(inner, list):
                out.extend(str(x) for x in inner)
                continue
        out.append(text)
    return out


def is_sandbox(node: Any) -> bool:
    """Узел принадлежит нити песочницы."""
    return SANDBOX_THREAD_TAG in _tags_of(node)


def is_trip(node: Any) -> bool:
    """Узел рождён в трипе (ослабленные гейты)."""
    return TRIP_TAG in _tags_of(node)


def is_quarantined(node: Any) -> bool:
    """Узел не должен покидать песочницу — по метке нити ИЛИ по метке трипа.

    Именно ИЛИ. Узел с `state:trip`, у которого по любой причине не оказалось
    тега нити, — самый опасный: он рождён при ослабленных гейтах, а выглядит
    как обычный. Пропустить его наружу дороже, чем лишний раз отфильтровать
    невинный узел песочницы.
    """
    tags = set(_tags_of(node))
    return SANDBOX_THREAD_TAG in tags or TRIP_TAG in tags


def _value_after(node: Any, prefix: str) -> Optional[str]:
    """Значение первого тега с этим префиксом; None, если тега нет."""
    for tag in _tags_of(node):
        if tag.startswith(prefix):
            value = tag[len(prefix):].strip()
            if value:
                return value
    return None


def run_id_of(node: Any) -> Optional[str]:
    """Идентификатор прогона из тега `run:<id>`."""
    return _value_after(node, RUN_PREFIX)


def arm_of(node: Any) -> Optional[str]:
    """Имя руки из тега `arm:<имя>`."""
    return _value_after(node, ARM_PREFIX)


def dose_of(node: Any) -> Optional[str]:
    """Уровень дозы из тега `dose:<уровень>`."""
    return _value_after(node, DOSE_PREFIX)


def write_gate_dose(node: Any) -> Dict[str, Any]:
    """Доза гейтов записи для узла (TS.2, мост между тегами и `run_write_gates`).

    Возвращает готовый набор именованных параметров для
    `mnemos.gates.run_write_gates` — или **пустой словарь**, если узел не из
    песочницы. Пустой словарь значит «ничего не меняем»: основной граф видит
    ровно те же гейты, что и до фазы S, и включить трип глобально нечем.

    Доза читается из тега `arm:<имя>` на самом узле. Узел песочницы без
    внятного тега руки трактуется как контроль (рука A) — то есть строже, а
    не мягче: неизвестная доза не должна открывать гейты.
    """
    if not is_sandbox(node) and not is_trip(node):
        return {}
    name = arm_of(node)
    try:
        cfg = arm(name) if name else ARMS["A"]
    except ValueError:
        cfg = ARMS["A"]
    if cfg.gate_mode == "reject" and not cfg.all_gates_flag and cfg.conf_pass == CONF_PASS_DEFAULT:
        return {}
    return {
        "trip_mode": cfg.gate_mode == "flag",
        "conf_pass": cfg.conf_pass,
        "all_gates_flag": cfg.all_gates_flag,
    }


def strip_quarantined(nodes: Sequence[Any]) -> List[Any]:
    """Убрать карантинные узлы из выдачи наружу (чекпойнт, выгрузка, пост).

    Порядок оставшихся сохраняется: вызывающий уже отсортировал их по своей
    релевантности, и переупорядочивать чужую выдачу мы не вправе.
    """
    return [n for n in (nodes or []) if not is_quarantined(n)]


