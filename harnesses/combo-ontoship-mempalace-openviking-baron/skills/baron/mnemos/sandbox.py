def arm(name: str) -> Arm:
    """Рука по имени. Неизвестное имя — отказ, а не молчаливый контроль.

    Опечатка в имени руки не должна превращаться в «ну пусть будет A»: тогда
    прогон запишет узлы трезвой руки с тегами дозы, и данные будут испорчены
    незаметно.
    """
    found = ARMS.get(str(name).strip()) if name is not None else None
    if found is None:
        raise ValueError(
            f"sandbox.arm: неизвестная рука {name!r}; допустимы: {', '.join(ARM_ORDER)}")
    return found


