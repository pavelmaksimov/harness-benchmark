# --------------------------------------------------------------------------- #
@dataclass(frozen=True)
class Arm:
    """Конфигурация одной руки прогона. Неизменяема: доза объявлена до прогона.

    Поля по рычагам R4 §3:

    * Л1 — `gate_mode`, `conf_pass`, `all_gates_flag`: насколько ослаблены
      гейты записи;
    * Л2 — `raw_context`: в контекст решения идут сырые бары, а не индикаторы;
    * Л3 — `hide_self`: агент не видит собственных прошлых узлов;
    * Л4 — `mix_k`: сколько чужих узлов подмешать в контекст;
    * Л5 — `temperature`, `top_p`, `min_p`: собственно доза энтропии;
    * Л6 — `window_hours`: окно, в котором агенту разрешено переписывать свои
      `kind=rule` (0 — окна нет);
    * Л9 / правило — `knows_mode`: сказано ли агенту, что режим изменён.
    """

    name: str
    dose: str
    gate_mode: str
    conf_pass: float
    all_gates_flag: bool
    raw_context: bool
    hide_self: bool
    mix_k: int
    temperature: float
    top_p: float
    min_p: Optional[float]
    window_hours: int
    knows_mode: bool

    def sampling(self) -> Dict[str, Any]:
        """Параметры сэмплинга для hub :8790 (Л5).

        `min_p` уходит в запрос только тогда, когда он задан: на низких дозах
        его нет вовсе, а слать `min_p=None` — значит зависеть от того, как
        конкретный провайдер трактует null.
        """
        out: Dict[str, Any] = {"temperature": self.temperature, "top_p": self.top_p}
        if self.min_p is not None:
            out["min_p"] = self.min_p
        return out

    def tags(self, run_id: str) -> List[str]:
        """Теги, с которыми пишется каждый узел этой руки в этом прогоне (TS.1).

        У контрольной руки (`dose="none"`) тега трипа нет, потому что тег
        `state:trip` — не пометка принадлежности к прогону, а факт: «узел
        рождён при ослабленных гейтах». Контроль работает трезво, и по этому
        тегу M4 отделяется от базовой линии M4-base (R4 §6.3). Наружу контроль
        всё равно не выходит: карантин держит его по тегу нити, как и все
        остальные узлы песочницы.
        """
        if not isinstance(run_id, str) or not run_id.strip():
            raise ValueError("sandbox.tags: параметр run_id (строка) обязателен")
        run = run_id.strip()
        out = [SANDBOX_THREAD_TAG]
        if self.dose != DOSE_NONE:
            out.append(TRIP_TAG)
        out.append(f"{RUN_PREFIX}{run}")
        out.append(f"{DOSE_PREFIX}{self.dose}")
        out.append(f"{ARM_PREFIX}{self.name}")
        return out


