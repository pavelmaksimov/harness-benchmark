# -*- coding: utf-8 -*-
"""TS.1 / TS.7 — карантин нити песочницы и рычаги Л1–Л9 как конфиг доз по рукам.

Модуль отвечает ровно на два вопроса и больше ни на что:

**1. Что считается песочницей и почему это не должно утечь (TS.1).** Всё, что
порождено в трипе, живёт в нити `thread:sandbox` с тегами `state:trip`,
`run:<id>`, `dose:<уровень>`, `arm:<рука>` и **не попадает** в основной граф до
трезвой фазы (R4 §3 Л1, ROADMAP фаза S). Карантин здесь — предикат, а не
фильтр стора: `is_quarantined` соединяет метку нити и метку трипа через **ИЛИ**,
потому что узел, у которого случайно потерялся тег нити, но остался `state:trip`,
опаснее, чем лишний отфильтрованный узел. Дешёвая ошибка — оставить в песочнице
лишнее; дорогая — выпустить наружу гипотезу, рождённую при ослабленных гейтах.

**2. Какие ручки крутит доза (TS.7).** `Arm` — это вся конфигурация руки одним
неизменяемым объектом: гейты записи (Л1), сырьё вместо индикаторов (Л2), запрет
самомодели (Л3), примесь чужих узлов (Л4), сэмплинг (Л5), окно пластичности
(Л6) и знание о режиме. Числа взяты из таблицы рук R4 §6.1 и
меняться могут только вместе с ней: протокол объявлен до прогона, подгонка
параметров по ходу превращает эксперимент в подбор.

Две развилки, которых в таблице §6.1 нет явными колонками, зафиксированы здесь:

* `gate_mode` у B1 — `reject`. В §6.1 у малой дозы в колонке гейтов стоит только
  `CONF_PASS` 0.35, `flag` появляется с B2. Малая доза ослабляет **порог**, а не
  вердикт; иначе между B1 и B2 нет разницы по Л1 и дозозависимость не читается.
* `raw_context` — выключен у контроля A и включён у всех доз: Л2 описан в R4 §3
  как часть трипа, а не как отдельная ручка руки.

**Что модуль не делает.** Ни ввода-вывода, ни стора, ни сети, ни решений о
записи: гейты (`mnemos/gates.py`) и сервер (`mnemos/server.py`) подключают эти
предикаты сами. Всё — чистые функции над снимками узлов.

`untouchable_rules` — список, который агент не может переписать даже в
окне пластичности Л6. Он тут, а не в конфиге роли, потому что это единственное
место, куда смотрят и гейты, и сторож; список из конфига можно подменить, из
кода — только правкой с ревью.
"""

